-- Written by the snaptrade-register-user-v2 Edge Function. Already exists on Prod and Dev, so this is a no-op there.
CREATE TABLE IF NOT EXISTS public.snaptrade_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  snaptrade_user_id text NOT NULL,
  snaptrade_user_secret uuid NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT snaptrade_users_pkey PRIMARY KEY (id),
  CONSTRAINT snaptrade_users_snaptrade_user_id_key UNIQUE (snaptrade_user_id)
);
